const lgpl = readFileSync(join(root, 'scripts', 'licenses', 'LGPL-2.1.txt'), 'utf-8').trim()
parts.push(
  `SoundTouchJS v0.3.0 — LGPL-2.1 (벤더링)\n` +
    `https://github.com/cutterbl/SoundTouchJS\n\n` +
    `이 앱은 soundtouchjs v0.3.0을 src/renderer/public/worklets/soundtouch-worklet.js 에\n` +
    `벤더링해 AudioWorklet 피치 시프트에 사용한다. 원본 출처와 수정 사실은 해당 파일\n` +
    `헤더에 명시되어 있으며, 파일은 앱 코드와 분리된 독립 스크립트로 유지된다.\n\n` +
    lgpl
)

