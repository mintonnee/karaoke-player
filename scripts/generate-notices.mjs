/**
 * THIRD-PARTY-NOTICES 생성기.
 * 번들되는 npm 패키지의 라이선스 전문 + 벤더링/런타임 다운로드 항목을 합쳐
 * src/renderer/src/generated/third-party-notices.txt 로 출력한다 (앱 내 설정 화면에서 표시).
 * 실행: pnpm gen:notices  (의존성 추가/변경 시 재실행 후 커밋)
 */

import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'fs'
import { dirname, join, resolve } from 'path'
import { fileURLToPath } from 'url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf-8'))

// dependencies 전부 + 번들되는 devDependencies (electron 본체 고지는 배포물의
// LICENSE.electron.txt / LICENSES.chromium.html 이 담당하지만 목록에는 포함한다)
const bundledPackages = [...Object.keys(pkg.dependencies ?? {}), 'react', 'react-dom', 'electron']

// eslint-disable-next-line @typescript-eslint/explicit-function-return-type -- 타입 표기 불가한 .mjs
function readLicenseText(pkgDir) {
  let entries
  try {
    entries = readdirSync(pkgDir)
  } catch {
    return null
  }
  const name = entries.find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f))
  return name ? readFileSync(join(pkgDir, name), 'utf-8').trim() : null
}

const divider = '\n' + '='.repeat(72) + '\n'
const parts = []

parts.push(
  `Karaoke Player — Third-Party Notices\n` +
    `이 문서는 이 애플리케이션에 포함되거나 실행 시 사용되는 서드파티 소프트웨어의\n` +
    `저작권 및 라이선스 고지를 담는다. (generated by scripts/generate-notices.mjs)`
)

// ── 1. 번들되는 npm 패키지 ──
for (const name of bundledPackages.sort()) {
  const pkgDir = join(root, 'node_modules', name)
  let meta
  try {
    meta = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf-8'))
  } catch {
    console.error(`skip (not installed): ${name}`)
    continue
  }
  const license = typeof meta.license === 'string' ? meta.license : JSON.stringify(meta.license)
  const text = readLicenseText(pkgDir)
  parts.push(
    `${name} v${meta.version} — ${license}\n${meta.homepage ?? ''}\n\n` +
      (text ?? '(라이선스 전문은 패키지 배포본에 포함되어 있지 않음 — 위 라이선스 식별자를 따른다)')
  )
}

